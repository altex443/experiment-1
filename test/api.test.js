const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createApp } = require('../server/app');
test('workout creation, session validation, and durable progress', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'forma-'));
  const file = path.join(dir, 'training.json');
  let app = createApp(file);
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  const base = 'http://localhost';
  const fetch = async (url, options = {}) => {
    const { Readable } = require('node:stream');
    const req = Readable.from(options.body ? [options.body] : []);
    req.url = new URL(url).pathname; req.method = options.method || 'GET';
    let body; const res = { statusCode: 200, setHeader() {}, end(value) { body = value; } };
    await app.handle(req, res);
    return { status: res.statusCode, json: async () => JSON.parse(body) };
  };
  const send = (method, url, body) => fetch(base + url, { method, body: body === undefined ? undefined : JSON.stringify(body) });
  const post = (url, body) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const state = await (await fetch(base + '/api/state')).json();
  assert.equal(state.exercises.length, 6);
  assert.equal((await post('/api/plans', { name: '', exerciseIds: [] })).status, 400);
  const result = await post('/api/plans', { name: 'Leg day', focus: 'Strength', exerciseIds: ['squat', 'squat'] });
  assert.equal(result.status, 201);
  const plan = await result.json();
  assert.equal(plan.exercises.length, 1);
  assert.equal((await post('/api/sessions', { planId: plan.id, completedSets: ['squat-99'], duration: 60 })).status, 400);
  assert.equal((await post('/api/sessions', { planId: plan.id, completedSets: ['squat-0', 'squat-0'], duration: 60 })).status, 400);
  assert.equal((await post('/api/sessions', { planId: plan.id, completedSets: [], duration: 60 })).status, 400);
  const session = await post('/api/sessions', { planId: plan.id, completedSets: ['squat-0', 'squat-1'], duration: 120 });
  assert.equal(session.status, 201);
  assert.equal((await session.json()).volume, 960);
  const saved = JSON.parse(await fs.readFile(file, 'utf8'));
  assert.equal(saved.sessions.length, 1);
  assert.equal(saved.plans.length, 2);
  const edited = await send('PUT', '/api/plans/' + plan.id, { name: 'Updated legs', focus: 'Hypertrophy', exercises: [{ id: 'squat', sets: 2, reps: 5, weight: 70 }] });
  assert.equal(edited.status, 200);
  assert.equal((await edited.json()).exercises[0].weight, 70);
  assert.equal((await send('PUT', '/api/settings', { weeklyGoal: 0 })).status, 400);
  assert.equal((await send('PUT', '/api/settings', { weeklyGoal: 3 })).status, 200);
  const payload = { planId: plan.id, completedSets: ['squat-0'], entries: [{ id: 'squat-0', reps: 6, weight: 75 }], duration: 90, requestId: 'retry-test' };
  const logged = await (await post('/api/sessions', payload)).json();
  assert.equal(logged.volume, 450);
  const retried = await (await post('/api/sessions', payload)).json();
  assert.equal(retried.id, logged.id);
  assert.equal((await post('/api/sessions', { ...payload, requestId: 'bad', entries: [{ id: 'squat-0', reps: -1, weight: 75 }] })).status, 400);
  assert.equal((await send('DELETE', '/api/plans/' + plan.id)).status, 200);
  const final = await (await fetch(base + '/api/state')).json();
  assert.equal(final.sessions.length, 2);
  assert.equal(final.settings.weeklyGoal, 3);
  app = createApp(file);
  const reloaded = await (await fetch(base + '/api/state')).json();
  assert.equal(reloaded.sessions.length, 2);
  assert.equal(reloaded.settings.weeklyGoal, 3);
  assert.equal((await post('/api/plans', { name: 'Bad sets', focus: 'Strength', exercises: [{ id: 'squat', sets: 0 }] })).status, 400);
  assert.equal((await send('PUT', '/api/plans/missing', { name: 'Missing', focus: 'Strength', exerciseIds: ['bench'] })).status, 404);
  assert.equal((await post('/api/sessions', { ...payload, requestId: 'invalid-entries', entries: [null] })).status, 400);
  const parallel = await Promise.all(['A', 'B'].map(name => post('/api/plans', { name, focus: 'Strength', exerciseIds: ['bench'] })));
  assert.ok(parallel.every(r => r.status === 201));
  const concurrentState = await (await fetch(base + '/api/state')).json();
  assert.equal(concurrentState.plans.length, 3);
  assert.equal((await send('DELETE', '/api/sessions/' + logged.id)).status, 200);
  assert.equal((await send('DELETE', '/api/sessions/' + logged.id)).status, 404);
  const malformed = await fetch(base + '/api/plans', { method: 'POST', body: '{broken' });
  assert.equal(malformed.status, 400);
  assert.equal((await fetch(base + '/api/missing')).status, 404);
});
